// Bakes the brand marks used by the homepage credibility section into a plain
// TS file, so neither icon package ships to the browser.
//
// Sources (both build-time only, in devDependencies):
//   @iconify-json/logos — full-colour marks (Gil Barbara's SVG Logos, CC0)
//   simple-icons        — single-colour marks, filled with each brand's own hex
//
// Re-run with:  node scripts/generate-tech-logos.mjs
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const logos = require('@iconify-json/logos/icons.json');
const simple = require('simple-icons');

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(__dirname, '..', 'components', 'home', 'techLogoData.ts');

/** Display name -> icon name in @iconify-json/logos (already full colour). */
const FROM_LOGOS = {
  Zapier: 'zapier',
  HubSpot: 'hubspot',
  Salesforce: 'salesforce',
  Airtable: 'airtable',
  Supabase: 'supabase',
  Notion: 'notion',
  Slack: 'slack',
  WhatsApp: 'whatsapp',
  Instagram: 'instagram',
  Stripe: 'stripe',
  Shopify: 'shopify',
  OpenAI: 'openai',
  Claude: 'claude',
  Twilio: 'twilio',
  Looker: 'looker',
  Tableau: 'tableau',
  Vercel: 'vercel',
  AWS: 'aws',
  Google: 'google',
  Gemini: 'google-gemini',
  'Power BI': 'microsoft-power-bi',
  Upwork: 'upwork',
};

/** Display name -> simple-icons export; filled with the brand's own hex. */
const FROM_SIMPLE = {
  n8n: 'siN8n',
  Make: 'siMake',
  'Google Sheets': 'siGooglesheets',
  Calendly: 'siCalendly',
  ElevenLabs: 'siElevenlabs',
  QuickBooks: 'siQuickbooks',
};

/**
 * Marks rendered in a solid tile, so the glyph is drawn in white rather than
 * the brand colour. The Iconify "upwork" entry is the full wordmark, which
 * reads as duplication next to the "Upwork" label — this is the "Up" glyph.
 */
const FROM_SIMPLE_WHITE = {
  'Upwork Glyph': 'siUpwork',
};

const entries = [];
const missing = [];

for (const [label, key] of Object.entries(FROM_LOGOS)) {
  const icon = logos.icons[key];
  if (!icon) { missing.push(label); continue; }
  const w = icon.width ?? logos.width ?? 24;
  const h = icon.height ?? logos.height ?? 24;
  entries.push([label, icon.body, `0 0 ${w} ${h}`]);
}

for (const [label, key] of Object.entries(FROM_SIMPLE)) {
  const icon = simple[key];
  if (!icon) { missing.push(label); continue; }
  entries.push([label, `<path fill="#${icon.hex}" d="${icon.path}"/>`, '0 0 24 24']);
}

for (const [label, key] of Object.entries(FROM_SIMPLE_WHITE)) {
  const icon = simple[key];
  if (!icon) { missing.push(label); continue; }
  entries.push([label, `<path fill="#fff" d="${icon.path}"/>`, '0 0 24 24']);
}

entries.sort((a, b) => a[0].localeCompare(b[0]));

const body = entries
  .map(([label, svg, viewBox]) => `  ${JSON.stringify(label)}: { viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(svg)} },`)
  .join('\n');

const file = `// AUTO-GENERATED by scripts/generate-tech-logos.mjs — do not edit by hand.
// Brand marks baked in at build time so no icon package ships to the browser.
// Sources: @iconify-json/logos (CC0) and simple-icons (CC0), both devDependencies.

export interface TechMark {
  viewBox: string;
  body: string;
}

export const TECH_MARKS: Record<string, TechMark> = {
${body}
};
`;

await fs.writeFile(OUT, file, 'utf8');
console.log(`Wrote ${entries.length} marks to components/home/techLogoData.ts`);
if (missing.length) console.log('Not found (will fall back to a monogram):', missing.join(', '));
